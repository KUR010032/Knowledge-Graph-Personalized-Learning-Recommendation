def generate_question(stem, options, answer, diff, exp_or_multi, multi=False, exp=None):
    if multi:
        explanation = exp
        qtype = "multiple_choice"
    else:
        explanation = exp_or_multi
        qtype = "single_choice"
    
    opts_formatted = []
    letters = ["A", "B", "C", "D"]
    for i, opt in enumerate(options):
        if i < len(letters):
            opts_formatted.append(f"{letters[i]}. {opt}")
    
    return {
        "stem": stem,
        "options": opts_formatted,
        "answer": answer,
        "difficulty": diff,
        "explanation": explanation,
        "question_type": qtype,
        "multi": multi
    }

